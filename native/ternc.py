#!/usr/bin/env python3
"""TERN native code generator.

Reads the JSON bytecode produced by `tern emit` and writes a C translation unit
in which every TERN function is a real C function, every jump a `goto` and
every opcode a few statements - there is no dispatch loop at run time.

    tern emit app.tern -o app.json
    python3 native/ternc.py app.json -o app.c
    ternc.py can also drive the whole pipeline: ternc.py app.tern -o app
"""
import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
RUNTIME = os.path.join(HERE, "runtime")


class CodegenError(Exception):
    pass


def c_string(text):
    """A C string literal for `text` (UTF-8 bytes, escaped)."""
    out = ['"']
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char == '"':
            out.append('\\"')
        elif char == "\\":
            out.append("\\\\")
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif 32 <= byte < 127:
            out.append(char)
        else:
            # Octal, not \xNN: a hex escape runs into any following hex digit
            # ("\x8db" is one character), which silently ate the next letter
            # after every non-ASCII byte.
            out.append("\\%03o" % byte)
    out.append('"')
    return "".join(out)


class Generator:
    def __init__(self, module, traces=True):
        if module.get("version") != 1:
            raise CodegenError("unsupported bytecode version %r" % module.get("version"))
        self.module = module
        self.protos = module["protos"]
        # Every compiled translation unit holds one or more modules: module 0 is
        # the script that was run, the rest are files it imports.
        self.modules = module.get("modules") or [
            {"name": module.get("module", "?"), "entry": module.get("entry", 0),
             "globals": [g["name"] for g in module.get("globals", [])], "exports": []}
        ]
        self.out = []
        self.traces = traces    # keep stack traces (a few cycles per call)
        self.types = {}          # (proto index, const index) -> C symbol for TypeObj
        self.type_decls = []

    # ---------------------------------------------------------------- helpers

    def emit(self, line=""):
        self.out.append(line)

    def constant_text(self, proto_index, const_index):
        consts = self.protos[proto_index]["consts"]
        if const_index >= len(consts):
            raise CodegenError("constant %d out of range in proto %d" % (const_index, proto_index))
        return consts[const_index]

    def name_of_constant(self, proto_index, const_index):
        const = self.constant_text(proto_index, const_index)
        if const.get("k") != "s":
            raise CodegenError("expected a string constant for a member name")
        return c_string(const["v"])

    @staticmethod
    def captured_slots(proto, protos):
        """Slots of `proto` that some child closure captures."""
        captured = set()
        for sub in proto["subs"]:
            if sub < 0:
                continue
            for from_local, index in protos[sub]["upvalues"]:
                if from_local:
                    captured.add(index)
        return captured

    # ------------------------------------------------------------------ output

    def generate(self):
        self.emit("// Generated by ternc.py from %s. Do not edit." % c_string(self.module.get("module", "?")))
        if not self.traces:
            self.emit("// Built with --no-traces: uncaught errors report one line.")
            self.emit("#define TERN_NO_TRACES 1")
        self.emit('#include "tern_rt.h"')
        self.emit("#include <signal.h>")
        self.emit()

        self.emit("// Single translation unit: including the runtime lets the C compiler")
        self.emit("// inline the value helpers straight into the generated code.")
        self.emit('#include "tern_rt.c"')
        self.emit()

        self.declare_protos()
        self.declare_constants()
        self.declare_types()
        self.define_protos()
        self.define_globals()
        self.define_functions()
        self.define_main()
        return "\n".join(self.out) + "\n"

    def declare_protos(self):
        self.emit("// ---- functions")
        for index in range(len(self.protos)):
            self.emit("static Value fn_%d(Closure *cl, int argc, Value *argv);" % index)
        for index in range(len(self.modules)):
            self.emit("static Value load_module_%d(void);" % index)
        self.emit()

    def declare_constants(self):
        self.emit("// ---- constants (filled in by init_consts)")
        for index, proto in enumerate(self.protos):
            count = len(proto["consts"])
            if count:
                self.emit("static Value K_%d[%d];" % (index, count))
            if proto["divs"]:
                entries = ", ".join("{%d, %dULL, %d}" % (d[0], d[1], d[2]) for d in proto["divs"])
                self.emit("static const DivMagic D_%d[] = {%s};" % (index, entries))
        self.emit()

    def declare_types(self):
        """Struct type constants become static TypeObj values."""
        for proto_index, proto in enumerate(self.protos):
            for const_index, const in enumerate(proto["consts"]):
                if const.get("k") != "type":
                    continue
                symbol = "T_%d_%d" % (proto_index, const_index)
                self.types[(proto_index, const_index)] = symbol
                fields = const["fields"]
                field_list = ", ".join(c_string(f) for f in fields) or "NULL"
                self.type_decls.append(
                    'static const char *%s_fields[] = {%s};' % (symbol, field_list)
                )
                self.type_decls.append("static Value %s_defaults[%d];" % (symbol, max(1, len(fields))))
                methods = const["methods"]
                if methods:
                    names = ", ".join(c_string(m[0]) for m in methods)
                    self.type_decls.append("static const char *%s_mnames[] = {%s};" % (symbol, names))
                    self.type_decls.append("static Closure *%s_methods[%d];" % (symbol, len(methods)))
                defaults = const.get("defprotos") or []
                if any(p >= 0 for p in defaults):
                    self.type_decls.append("static Closure *%s_defproto[%d];"
                                           % (symbol, max(1, len(fields))))
                    protos = "%s_defproto" % symbol
                else:
                    protos = "NULL"
                self.type_decls.append(
                    "static TypeObj %s = {{O_TYPE}, %s, %d, %s, %s_defaults, %d, %s, %s, %s, NULL};"
                    % (
                        symbol,
                        c_string(const["name"]),
                        len(fields),
                        "%s_fields" % symbol if fields else "NULL",
                        symbol,
                        len(methods),
                        "%s_mnames" % symbol if methods else "NULL",
                        "%s_methods" % symbol if methods else "NULL",
                        protos,
                    )
                )

        if self.type_decls:
            self.emit("// ---- struct types")
            self.emit("\n".join(self.type_decls))
            self.emit()

    def define_protos(self):
        self.emit("// ---- prototypes")
        for index, proto in enumerate(self.protos):
            consts = "K_%d" % index if proto["consts"] else "NULL"
            divs = "D_%d" % index if proto["divs"] else "NULL"
            name = c_string(proto["name"]) if proto["name"] is not None else "NULL"
            self.emit(
                "static Proto P_%d = { fn_%d, %s, %d, %d, %d, %d, %d, %d, %d, %s, %s };"
                % (
                    index, index, name,
                    proto["params"], proto["required"], proto["locals"], max(4, proto["stack"]),
                    1 if proto["rest"] else 0, 1 if proto["method"] else 0,
                    len(proto["upvalues"]),
                    consts, divs,
                )
            )
        self.emit()

    def define_globals(self):
        self.emit("// ---- module globals")
        for index, module in enumerate(self.modules):
            count = len(module["globals"])
            self.emit("static Value G_%d[%d];" % (index, max(1, count)))
            names = ", ".join(c_string(name) for name in module["globals"]) or "NULL"
            self.emit("static const char *GN_%d[%d] = {%s};" % (index, max(1, count), names))
            self.emit("static Value MOD_%d;" % index)
            self.emit("static int MODSTATE_%d;" % index)
        self.emit()

    # ------------------------------------------------------------- functions

    def define_functions(self):
        for index, proto in enumerate(self.protos):
            self.function(index, proto)

    def function(self, index, proto):
        captured = self.captured_slots(proto, self.protos)
        locals_count = max(1, proto["locals"])
        stack = max(4, proto["stack"])

        # A function with a `try` block can be resumed by longjmp, so its frame
        # has to live in memory rather than in callee-saved registers.
        self.has_try = any(instr[0] == "EnterTry" for instr in proto["code"])
        qual = "volatile " if self.has_try else ""

        self.emit("// ---- %s" % (proto["name"] or "<anonymous>"))
        self.emit("static Value fn_%d(Closure *cl, int argc, Value *argv) {" % index)
        self.emit("    (void)cl; (void)argc; (void)argv;")
        self.emit("    %sValue lc[%d];" % (qual, locals_count))
        if captured:
            self.emit("    Cell *cap[%d];" % locals_count)
        self.emit("    %sValue st[%d];" % (qual, stack))
        self.emit("    %sint sp = 0; (void)sp;" % qual)
        if self.has_try:
            self.emit("    TernTry *try_base = tern_try_top; (void)try_base;")
        self.try_stack = []

        for slot in sorted(captured):
            self.emit("    cap[%d] = cell_new(v_nil());" % slot)

        base = 1 if proto["method"] else 0
        if proto["method"]:
            self.emit("    lc[0] = argc > 0 ? argv[0] : v_nil();")

        params = proto["params"]
        for i in range(params):
            # Methods receive their receiver as argv[0], so declared parameters
            # start one slot later.
            source = base + i
            slot = base + i
            assignment = "argc > %d ? argv[%d] : v_missing()" % (source, source)
            if slot in captured:
                self.emit("    cap[%d]->value = %s;" % (slot, assignment))
            else:
                self.emit("    lc[%d] = %s;" % (slot, assignment))

        # `...rest` collects everything past the declared parameters into a list.
        if proto["rest"]:
            slot = base + params
            rest_at = base + params
            assignment = ("tern_list_from(argc > %d ? argc - %d : 0,"
                          " argc > %d ? &argv[%d] : NULL)" % (rest_at, rest_at, rest_at, rest_at))
            if slot in captured:
                self.emit("    cap[%d]->value = %s;" % (slot, assignment))
            else:
                self.emit("    lc[%d] = %s;" % (slot, assignment))

        lines = proto.get("lines") or []
        body_start = len(self.out)

        for i, instruction in enumerate(proto["code"]):
            self.emit("L%d:" % i)
            # Keep the current source line available for traces. Storing it only
            # when the line changes keeps the cost at a few stores per function.
            if lines:
                line_here = lines[i] if i < len(lines) else 0
                previous = lines[i - 1] if i > 0 else -1
                if line_here != previous:
                    self.emit("    tern_set_line(%d);" % line_here)
            self.instruction(index, proto, instruction, i)

        # Jumps may target one past the last instruction (a try whose handler
        # falls off the end of the function).
        self.emit("L%d:" % len(proto["code"]))
        self.emit("    return v_nil();")
        self.emit("}")
        self.emit()

        if lines:
            self.record_jump_targets(body_start, len(self.out), lines)

    def record_jump_targets(self, start, end, lines):
        """Store the source line at every label a jump can land on.

        Emitting at line changes alone would leave the wrong line in place when
        a backward jump lands on an instruction whose line it shares with the
        instruction before it in the listing, so every jump target gets a store
        unless it already has one.
        """
        import re
        body = self.out[start:end]
        pending = set()
        for text in body:
            pending.update(int(target) for target in re.findall(r"goto L(\d+)", text))
        if not pending:
            return
        for position, text in enumerate(body):
            match = re.match(r"L(\d+):$", text.strip())
            if not match:
                continue
            target = int(match.group(1))
            if target not in pending or target >= len(lines):
                continue
            following = body[position + 1] if position + 1 < len(body) else ""
            if "tern_set_line(" in following:
                continue
            if target == 0:
                continue  # instruction 0 always stores its own line
            body[position + 1:position + 1] = ["    tern_set_line(%d);" % lines[target]]

    def loc(self, slot, captured):
        return "cap[%d]->value" % slot if slot in captured else "lc[%d]" % slot

    def locref(self, slot, captured):
        return "cap[%d]->value" % slot if slot in captured else "lc[%d]" % slot

    def globals_of(self, proto):
        """C symbol for the global array of the module that owns `proto`."""
        return "G_%d" % proto.get("module", 0)

    def instruction(self, index, proto, instruction, position):
        op, a, b, c = instruction
        captured = self.captured_slots(proto, self.protos)
        out = []

        def line(text):
            out.append("    " + text)

        if op == "Nop":
            pass

        elif op == "Pop":
            line("sp--;")

        elif op == "Dup":
            line("st[sp] = st[sp - 1]; sp++;")

        elif op == "Swap":
            line("{ Value t = st[sp - 1]; st[sp - 1] = st[sp - 2]; st[sp - 2] = t; }")

        elif op == "LoadNil":
            line("st[sp++] = v_nil();")
        elif op == "LoadTrue":
            line("st[sp++] = v_bool(true);")
        elif op == "LoadFalse":
            line("st[sp++] = v_bool(false);")
        elif op == "LoadInt":
            line("st[sp++] = v_int(%d);" % a)
        elif op == "LoadConst":
            line("st[sp++] = K_%d[%d];" % (index, a))
        elif op == "LoadLocal":
            line("st[sp++] = %s;" % self.loc(a, captured))
        elif op == "StoreLocal":
            line("%s = st[--sp];" % self.loc(a, captured))
        elif op == "LoadGlobal":
            line("st[sp++] = %s[%d];" % (self.globals_of(proto), a))
        elif op == "StoreGlobal":
            line("%s[%d] = st[--sp];" % (self.globals_of(proto), a))
        elif op == "LoadUpvalue":
            line("st[sp++] = cl->up[%d]->value;" % a)
        elif op == "StoreUpvalue":
            line("cl->up[%d]->value = st[--sp];" % a)
        elif op == "CloseUpvalues":
            pass   # captured locals are heap cells already

        elif op == "ArgOrJump":
            line("if (%s.tag != T_MISSING) goto L%d;" % (self.loc(a, captured), b))

        elif op == "IncLocal":
            slot = self.loc(a, captured)
            line("{ Value v = %s;" % slot)
            line("  if (v.tag == T_INT) %s = v_int(v.as.i + %d);" % (slot, b))
            line("  else if (v.tag == T_FLOAT) %s = v_float(v.as.f + %d);" % (slot, b))
            line('  else tern_panic("TypeError", "cannot increment %%s", tern_type_name(v)); }')

        # ---- members
        elif op == "LoadField":
            line("st[sp - 1] = tern_get_member(st[sp - 1], %s);" % self.name_of_constant(index, a))

        elif op == "Length":
            name = self.name_of_constant(index, a)
            line("{ Value *t = NP(&st[sp - 1]);")
            line("  if (t->tag == T_OBJ && (t->as.o->type == O_STR || t->as.o->type == O_LIST ||")
            line("                          t->as.o->type == O_MAP)) *t = v_int(tern_length(*t));")
            line("  else *t = tern_get_member(*t, %s); }" % name)

        elif op in ("StoreField", "StoreFieldDiscard"):
            name = self.name_of_constant(index, a)
            line("{ Value v = st[--sp]; Value t = st[--sp];")
            line("  tern_set_member(t, %s, v);" % name)
            line("  %s}" % ("st[sp++] = v; " if op == "StoreField" else ""))

        elif op == "LoadIndex":
            line("{ Value i = st[--sp]; st[sp - 1] = tern_get_index(st[sp - 1], i); }")

        elif op in ("StoreIndex", "StoreIndexDiscard"):
            line("{ Value v = st[--sp]; Value i = st[--sp]; Value t = st[--sp];")
            line("  tern_set_index(t, i, v);")
            line("  %s}" % ("st[sp++] = v; " if op == "StoreIndex" else ""))

        # ---- aggregates
        elif op == "NewList":
            line("{ int base = sp - %d; List *l = list_new(%d);" % (a, a))
            line("  for (int i = 0; i < %d; i++) list_push(l, st[base + i]);" % a)
            line("  sp = base; st[sp++] = v_obj((Obj *)l); }")

        elif op == "NewMap":
            line("{ int base = sp - %d; Map *m = map_new();" % (2 * a))
            line("  for (int i = 0; i < %d; i++) map_set(m, st[base + 2 * i], st[base + 2 * i + 1]);" % a)
            line("  sp = base; st[sp++] = v_obj((Obj *)m); }")

        elif op == "NewInstance":
            symbol = self.types.get((index, a))
            if symbol is None:
                raise CodegenError("NewInstance without a struct constant in proto %d" % index)
            line("{ int base = sp - %d;" % b)
            line("  Value inst = tern_new_instance(&%s, %d, NP(&st[base]));" % (symbol, b))
            line("  sp = base; st[sp++] = inst; }")

        elif op == "NewRange":
            line("{ Value e = st[--sp]; Value s = st[--sp];")
            line("  int64_t from = s.tag == T_INT ? s.as.i : (int64_t)v_as_double(s);")
            line("  int64_t to = e.tag == T_INT ? e.as.i : (int64_t)v_as_double(e);")
            line("  st[sp++] = v_obj((Obj *)range_make(from, to, %s, 1)); }" % ("true" if a else "false"))

        elif op == "Concat":
            line("st[sp - %d] = tern_concat(NP(&st[sp - %d]), %d); sp -= %d;" % (a, a, a, a - 1))

        # ---- arithmetic
        elif op in ("Add", "Sub", "Mul", "Div", "Mod", "Pow", "BAnd", "BOr", "BXor", "Shl", "Shr"):
            function = {
                "Add": "tern_add", "Sub": "tern_sub", "Mul": "tern_mul", "Div": "tern_div",
                "Mod": "tern_mod", "Pow": "tern_pow", "BAnd": "tern_band", "BOr": "tern_bor",
                "BXor": "tern_bxor", "Shl": "tern_shl", "Shr": "tern_shr",
            }[op]
            line("{ Value b = st[--sp], a = st[sp - 1];")
            if op in ("Add", "Sub", "Mul"):
                symbol = {"Add": "+", "Sub": "-", "Mul": "*"}[op]
                builtin = {"Add": "__builtin_add_overflow", "Sub": "__builtin_sub_overflow",
                           "Mul": "__builtin_mul_overflow"}[op]
                line("  int64_t r;")
                line("  if (a.tag == T_INT && b.tag == T_INT && !%s(a.as.i, b.as.i, &r))" % builtin)
                line("      st[sp - 1] = v_int(r);")
                line('  else if (a.tag == T_FLOAT && b.tag == T_FLOAT) st[sp - 1] = v_float(a.as.f %s b.as.f);' % symbol)
                line("  else st[sp - 1] = %s(a, b); }" % function)
            elif op in ("BAnd", "BOr", "BXor", "Shl", "Shr"):
                symbol = {"BAnd": "&", "BOr": "|", "BXor": "^", "Shl": "<<", "Shr": ">>"}[op]
                line("  if (a.tag == T_INT && b.tag == T_INT)")
                if op in ("Shl", "Shr"):
                    line("      st[sp - 1] = v_int((int64_t)((uint64_t)a.as.i %s (b.as.i & 63)));" % symbol)
                else:
                    line("      st[sp - 1] = v_int(a.as.i %s b.as.i);" % symbol)
                line("  else st[sp - 1] = %s(a, b); }" % function)
            else:
                line("  st[sp - 1] = %s(a, b); }" % function)

        elif op == "Neg":
            line("{ Value *a = NP(&st[sp - 1]);")
            line("  if (a->tag == T_INT) a->as.i = a->as.i == INT64_MIN ? a->as.i : -a->as.i;")
            line("  else *a = tern_neg(*a); }")
        elif op == "Not":
            line("st[sp - 1] = v_bool(!v_truthy(st[sp - 1]));")
        elif op == "BNot":
            line("st[sp - 1] = tern_bnot(st[sp - 1]);")

        # ---- comparison
        elif op in ("Eq", "Ne", "Lt", "Le", "Gt", "Ge"):
            compare = {"Eq": "== 0", "Ne": "!= 0", "Lt": "< 0", "Le": "<= 0", "Gt": "> 0", "Ge": ">= 0"}[op]
            line("{ Value b = st[--sp], a = st[sp - 1];")
            if op == "Eq":
                line("  if (a.tag == T_INT && b.tag == T_INT) st[sp - 1] = v_bool(a.as.i == b.as.i);")
                line("  else st[sp - 1] = v_bool(tern_equal(a, b)); }")
            elif op == "Ne":
                line("  if (a.tag == T_INT && b.tag == T_INT) st[sp - 1] = v_bool(a.as.i != b.as.i);")
                line("  else st[sp - 1] = v_bool(!tern_equal(a, b)); }")
            else:
                symbol = {"Lt": "<", "Le": "<=", "Gt": ">", "Ge": ">="}[op]
                line("  if (a.tag == T_INT && b.tag == T_INT) st[sp - 1] = v_bool(a.as.i %s b.as.i);" % symbol)
                line("  else st[sp - 1] = v_bool(tern_compare(a, b).as.i %s); }" % compare)

        # ---- fused local arithmetic
        elif op in ("AddLocalLocal", "SubLocalLocal", "MulLocalLocal", "DivLocalLocal", "ModLocalLocal"):
            function = {"AddLocalLocal": "tern_add", "SubLocalLocal": "tern_sub", "MulLocalLocal": "tern_mul",
                        "DivLocalLocal": "tern_div", "ModLocalLocal": "tern_mod"}[op]
            symbol = {"AddLocalLocal": "+", "SubLocalLocal": "-", "MulLocalLocal": "*"}.get(op)
            builtin = {"AddLocalLocal": "__builtin_add_overflow", "SubLocalLocal": "__builtin_sub_overflow",
                       "MulLocalLocal": "__builtin_mul_overflow"}.get(op)
            line("{ Value x = %s, y = %s;" % (self.loc(a, captured), self.loc(b, captured)))
            if symbol:
                line("  int64_t r;")
                line("  if (x.tag == T_INT && y.tag == T_INT && !%s(x.as.i, y.as.i, &r))" % builtin)
                line("      st[sp++] = v_int(r);")
                line("  else st[sp++] = %s(x, y); }" % function)
            else:
                line("  st[sp++] = %s(x, y); }" % function)

        elif op in ("AddLocalConst", "SubLocalConst", "MulLocalConst", "DivLocalConst", "ModLocalConst"):
            const = self.constant_text(index, b)
            function = {"AddLocalConst": "tern_add", "SubLocalConst": "tern_sub", "MulLocalConst": "tern_mul",
                        "DivLocalConst": "tern_div", "ModLocalConst": "tern_mod"}[op]
            symbol = {"AddLocalConst": "+", "SubLocalConst": "-", "MulLocalConst": "*"}.get(op)
            builtin = {"AddLocalConst": "__builtin_add_overflow", "SubLocalConst": "__builtin_sub_overflow",
                       "MulLocalConst": "__builtin_mul_overflow"}.get(op)
            literal = self.literal(const)
            raw = self.raw_int(const) if const["k"] == "i" else None
            line("{ Value x = %s;" % self.loc(a, captured))
            if symbol and raw is not None:
                line("  int64_t r;")
                line("  if (x.tag == T_INT && !%s(x.as.i, (int64_t)%s, &r)) st[sp++] = v_int(r);" % (builtin, raw))
                line("  else st[sp++] = %s(x, %s); }" % (function, literal))
            else:
                line("  st[sp++] = %s(x, %s); }" % (function, literal))

        elif op == "ModLocalConstMagic":
            division = proto["divs"][b]
            divisor, magic, shift = division
            line("{ Value *a = &%s;" % self.locref(a, captured))
            line("  if (a->tag == T_INT) {")
            line("      int64_t x = a->as.i;")
            line("      uint64_t mag = %dULL, magnitude = x < 0 ? (uint64_t)(-(x + 1)) + 1 : (uint64_t)x;" % magic)
            line("      uint64_t q = (uint64_t)(((__uint128_t)magnitude * mag) >> 64) >> %d;" % shift)
            line("      int64_t rem = (int64_t)(magnitude - q * (uint64_t)%d);" % divisor)
            # The reciprocal is off by one for a handful of values (most notably
            # INT64_MIN): fall back to a hardware remainder. That remainder is
            # already signed, so it must not be negated again.
            line("      if ((uint64_t)rem >= (uint64_t)%d) rem = x %% %d;" % (divisor, divisor))
            line("      else rem = x < 0 ? -rem : rem;")
            line("      st[sp++] = v_int(rem);")
            line("  } else st[sp++] = tern_mod(*a, v_int(%d)); }" % divisor)

        # ---- fused stores
        elif op in ("AddStoreLocal", "SubStoreLocal", "MulStoreLocal", "DivStoreLocal", "ModStoreLocal"):
            function = {"AddStoreLocal": "tern_add", "SubStoreLocal": "tern_sub", "MulStoreLocal": "tern_mul",
                        "DivStoreLocal": "tern_div", "ModStoreLocal": "tern_mod"}[op]
            symbol = {"AddStoreLocal": "+", "SubStoreLocal": "-", "MulStoreLocal": "*"}.get(op)
            builtin = {"AddStoreLocal": "__builtin_add_overflow", "SubStoreLocal": "__builtin_sub_overflow",
                       "MulStoreLocal": "__builtin_mul_overflow"}.get(op)
            slot = self.loc(a, captured)
            line("{ Value b = st[--sp], x = st[--sp];")
            if symbol:
                line("  int64_t r;")
                line("  if (x.tag == T_INT && b.tag == T_INT && !%s(x.as.i, b.as.i, &r)) %s = v_int(r);" % (builtin, slot))
                line("  else %s = %s(x, b); }" % (slot, function))
            else:
                line("  %s = %s(x, b); }" % (slot, function))

        elif op in ("AddLocalConstStore", "SubLocalConstStore"):
            # Unlike AddLocalConst, the B operand here is the small integer delta
            # itself (used by `for (let i = ...; i += 1)`), not a constant index.
            symbol = "+" if op == "AddLocalConstStore" else "-"
            builtin = "__builtin_add_overflow" if op == "AddLocalConstStore" else "__builtin_sub_overflow"
            function = "tern_add" if op == "AddLocalConstStore" else "tern_sub"
            slot = self.locref(a, captured)
            line("{ Value *p = NP(&%s); int64_t r;" % slot)
            line("  if (p->tag == T_INT && !%s(p->as.i, (int64_t)%d, &r)) p->as.i = r;" % (builtin, b))
            line("  else *p = %s(*p, v_int(%d)); }" % (function, b))

        elif op in ("AddLocalLocalStore", "SubLocalLocalStore"):
            symbol = "+" if op == "AddLocalLocalStore" else "-"
            builtin = "__builtin_add_overflow" if op == "AddLocalLocalStore" else "__builtin_sub_overflow"
            function = "tern_add" if op == "AddLocalLocalStore" else "tern_sub"
            slot = self.locref(a, captured)
            line("{ Value *p = &%s; Value y = %s; int64_t r;" % (slot, self.loc(b, captured)))
            line("  if (p->tag == T_INT && y.tag == T_INT && !%s(p->as.i, y.as.i, &r)) p->as.i = r;" % builtin)
            line("  else *p = %s(*p, y); }" % function)

        elif op in ("AddLocalStack", "SubLocalStack"):
            function = "tern_add" if op == "AddLocalStack" else "tern_sub"
            builtin = "__builtin_add_overflow" if op == "AddLocalStack" else "__builtin_sub_overflow"
            slot = self.locref(a, captured)
            line("{ Value *p = &%s; Value y = st[--sp]; int64_t r;" % slot)
            line("  if (p->tag == T_INT && y.tag == T_INT && !%s(p->as.i, y.as.i, &r)) p->as.i = r;" % builtin)
            line("  else *p = %s(*p, y); }" % function)

        elif op == "IncLocalJump":
            slot = self.locref(a, captured)
            line("{ Value *p = &%s;" % slot)
            line("  if (p->tag == T_INT) p->as.i += %d; else *p = tern_add(*p, v_int(%d));" % (b, b))
            line("  goto L%d; }" % c)

        # ---- control flow
        elif op == "Jump":
            line("goto L%d;" % a)
        elif op == "JumpIfFalse":
            line("if (!v_truthy(st[--sp])) goto L%d;" % a)
        elif op == "JumpIfTrue":
            line("if (v_truthy(st[--sp])) goto L%d;" % a)
        elif op == "JumpIfFalseLocal":
            line("if (!v_truthy(%s)) goto L%d;" % (self.loc(a, captured), b))
        elif op == "JumpIfTrueLocal":
            line("if (v_truthy(%s)) goto L%d;" % (self.loc(a, captured), b))
        elif op == "JumpIfFalseKeep":
            line("if (!v_truthy(st[sp - 1])) goto L%d;" % a)
        elif op == "JumpIfTrueKeep":
            line("if (v_truthy(st[sp - 1])) goto L%d;" % a)
        elif op == "JumpIfNotNullKeep":
            line("if (st[sp - 1].tag != T_NIL) goto L%d;" % a)
        elif op == "JumpIfNotList":
            line("if (!v_is_list(%s)) goto L%d;" % (self.loc(a, captured), b))
        elif op == "JumpIfNotNumber":
            line("if (!v_is_num(%s)) goto L%d;" % (self.loc(a, captured), b))

        elif op == "JumpCmp":
            condition = {0: "cmp < 0", 1: "cmp <= 0", 2: "cmp > 0", 3: "cmp >= 0"}.get(a)
            if condition:
                line("{ Value b = st[--sp], a = st[--sp]; int cmp;")
                line("  if (a.tag == T_INT && b.tag == T_INT) cmp = a.as.i < b.as.i ? -1 : (a.as.i > b.as.i ? 1 : 0);")
                line("  else if (v_is_num(a) && v_is_num(b)) cmp = v_as_double(a) < v_as_double(b) ? -1 : (v_as_double(a) > v_as_double(b) ? 1 : 0);")
                line("  else cmp = (int)tern_compare(a, b).as.i;")
                line("  if ((%s) == %s) goto L%d; }" % (condition, "true" if c else "false", b))
            else:
                # Eq / Ne compare values for equality; they never order them, so
                # they must not go through tern_compare.
                compare = "tern_equal(a, b)" if a == 4 else "!tern_equal(a, b)"
                line("{ Value b = st[--sp], a = st[--sp];")
                line("  if ((%s) == %s) goto L%d; }" % (compare, "true" if c else "false", b))

        elif op in ("ForPrepLt", "ForPrepLe", "ForPrepGt", "ForPrepGe"):
            test = {"ForPrepLt": "<", "ForPrepLe": "<=", "ForPrepGt": ">", "ForPrepGe": ">="}[op]
            line("{ Value cv = %s;" % self.loc(a, captured))
            line('  if (cv.tag != T_INT) tern_panic("TypeError", "cannot compare %%s with an integer loop bound", tern_type_name(cv));')
            line("  if (!(cv.as.i %s %d)) goto L%d; }" % (test, b, c))

        elif op in ("ForNextLt", "ForNextLe", "ForNextGt", "ForNextGe"):
            test = {"ForNextLt": "<", "ForNextLe": "<=", "ForNextGt": ">", "ForNextGe": ">="}[op]
            step = "-1" if op in ("ForNextGt", "ForNextGe") else "+1"
            slot = self.locref(a, captured)
            line("{ Value *p = &%s;" % slot)
            line('  if (p->tag != T_INT) tern_panic("TypeError", "loop counter became %%s; it must stay an integer", tern_type_name(*p));')
            line("  int64_t v = p->as.i %s; p->as.i = v;" % step)
            line("  if (v %s %d) goto L%d; }" % (test, b, c))

        elif op in ("JumpLtLocalInt", "JumpLeLocalInt", "JumpGtLocalInt", "JumpGeLocalInt",
                   "JumpEqLocalInt", "JumpNeLocalInt"):
            test = {"JumpLtLocalInt": "<", "JumpLeLocalInt": "<=", "JumpGtLocalInt": ">",
                    "JumpGeLocalInt": ">=", "JumpEqLocalInt": "==", "JumpNeLocalInt": "!="}[op]
            # Fused compares branch when the test is *not* taken (see VM).
            line("{ Value cv = %s; int take;" % self.loc(a, captured))
            line("  if (cv.tag == T_INT) take = cv.as.i %s %d;" % (test, b))
            line("  else { Value r = tern_compare(cv, v_int(%d)); take = r.as.i %s 0; }" % (b, test))
            line("  if (!take) goto L%d; }" % c)

        elif op in ("JumpLtLocalLocal", "JumpLeLocalLocal", "JumpGtLocalLocal", "JumpGeLocalLocal",
                   "JumpEqLocalLocal", "JumpNeLocalLocal"):
            test = {"JumpLtLocalLocal": "<", "JumpLeLocalLocal": "<=", "JumpGtLocalLocal": ">",
                    "JumpGeLocalLocal": ">=", "JumpEqLocalLocal": "==", "JumpNeLocalLocal": "!="}[op]
            # Fused compares branch when the test is *not* taken (see VM).
            line("{ Value x = %s, y = %s; int take;" % (self.loc(a, captured), self.loc(b, captured)))
            line("  if (x.tag == T_INT && y.tag == T_INT) take = x.as.i %s y.as.i;" % test)
            if op in ("JumpEqLocalLocal", "JumpNeLocalLocal"):
                line("  else take = tern_equal(x, y) %s 0;" % ("==" if test == "==" else "!="))
            else:
                line("  else take = tern_compare(x, y).as.i %s 0;" % test)
            line("  if (!take) goto L%d; }" % c)

        # ---- calls
        elif op in ("Call", "CallLocal", "CallGlobal", "Invoke"):
            # No line store here: every instruction is reached either by
            # fall-through or through a label that stores its line (see
            # `record_jump_targets`), so the current line is already right.
            if op == "Call":
                line("{ int n = %d; Value r = tern_call(st[sp - n - 1], n, NP(&st[sp - n])); sp -= n; st[sp - 1] = r; }" % a)
            elif op == "CallLocal":
                line("{ int n = %d; Value r = tern_call(%s, n, NP(&st[sp - n])); sp -= n; st[sp++] = r; }"
                     % (a, self.loc(b, captured)))
            elif op == "CallGlobal":
                line("{ int n = %d; Value r = tern_call(%s[%d], n, NP(&st[sp - n])); sp -= n; st[sp++] = r; }"
                     % (a, self.globals_of(proto), b))
            else:
                line("{ int n = %d; Value r = tern_invoke(st[sp - n - 1], %s, n, NP(&st[sp - n])); sp -= n; st[sp - 1] = r; }"
                     % (b, self.name_of_constant(index, a)))
        elif op in ("Return", "ReturnNil", "ReturnLocal"):
            if self.has_try:
                line("tern_try_top = try_base;")
            if op == "Return":
                line("return st[--sp];")
            elif op == "ReturnNil":
                line("return v_nil();")
            else:
                line("return %s;" % self.loc(a, captured))

        # ---- closures
        elif op == "MakeClosure":
            sub = proto["subs"][a]
            if sub < 0:
                raise CodegenError("MakeClosure refers to a missing prototype")
            upvalues = self.protos[sub]["upvalues"]
            line("{ Closure *c = closure_new(&P_%d, %d);" % (sub, len(upvalues)))
            for slot, (from_local, upindex) in enumerate(upvalues):
                source = "cap[%d]" % upindex if from_local else "cl->up[%d]" % upindex
                line("  c->up[%d] = %s;" % (slot, source))
            line("  st[sp++] = v_obj((Obj *)c); }")

        # ---- conversions and iteration
        elif op == "ToString":
            line("st[sp - 1] = tern_to_string(st[sp - 1]);")
        elif op == "TypeOf":
            line("{ Value v = st[--sp]; st[sp++] = str_from_cstr(tern_type_name(v)); }")
        elif op == "IterNew":
            line("st[sp - 1] = tern_iter_new(st[sp - 1]);")
        elif op == "IterNext":
            # The iterator value is consumed: one stack slot is popped whatever
            # happens, the bindings are pushed only when there is a next item.
            line("{ Value iterator = st[--sp], first, second;")
            line("  if (!tern_iter_next(iterator, &first, &second)) goto L%d;" % a)
            line("  st[sp++] = first;")
            if b > 1:
                line("  st[sp++] = second; }")
            else:
                line("}")
        elif op == "In":
            line("{ Value c = st[--sp], i = st[--sp]; st[sp++] = v_bool(tern_contains(c, i)); }")
        elif op == "Slice":
            line("{ Value e = st[--sp], s = st[--sp], t = st[--sp];")
            line("  st[sp++] = tern_slice(t, s, e, %s); }" % ("true" if a else "false"))

        # ---- exceptions
        elif op == "EnterTry":
            # One C block per try: setjmp records the frame, and a throw jumps
            # straight back here with the error value pushed on the stack.
            guard = "try_%d" % position
            self.try_stack.append(guard)
            line("{ TernTry %s;" % guard)
            line("  %s.prev = tern_try_top; tern_try_top = &%s; %s.sp = sp;" % (guard, guard, guard))
            line("  %s.depth = tern_call_depth;" % guard)
            line("  %s.frames = tern_frame_cur;" % guard)
            line("  if (setjmp(%s.env)) {" % guard)
            line("      sp = %s.sp; tern_call_depth = %s.depth; tern_frame_cur = %s.frames;" % (guard, guard, guard))
            line("      st[sp++] = tern_thrown; goto L%d; }" % a)

        elif op == "ExitTry":
            if self.try_stack:
                guard = self.try_stack.pop()
                line("{ tern_try_top = %s.prev; } }" % guard)
            else:
                line("{ /* ExitTry without a matching EnterTry */ }")

        elif op == "Throw":
            line("{ Value error = st[--sp]; tern_raise(error); }")

        elif op == "LoadModule":
            const = self.constant_text(index, a)
            if const.get("k") != "module":
                raise CodegenError("LoadModule expects a module constant")
            line("st[sp++] = load_module_%d();" % const["mod"])

        else:
            raise CodegenError("unknown opcode %r in function %s" % (op, proto["name"] or "<anonymous>"))

        self.out.extend(out)

    @staticmethod
    def raw_int(const):
        value = int(const["v"])
        return "%dLL" % value if abs(value) >= 2**31 else str(value)

    @staticmethod
    def literal(const):
        kind = const["k"]
        if kind == "i":
            value = int(const["v"])
            return "v_int(%dLL)" % value if abs(value) >= 2**31 else "v_int(%d)" % value
        if kind == "f":
            import math
            value = float(const["v"])
            if math.isnan(value):
                return "v_float(NAN)"
            if math.isinf(value):
                return "v_float(-INFINITY)" if value < 0 else "v_float(INFINITY)"
            return "v_float(%r)" % value
        if kind == "s":
            return "str_from_cstr(%s)" % c_string(const["v"])
        if kind == "b":
            return "v_bool(%s)" % ("true" if const["v"] else "false")
        if kind == "nil":
            return "v_nil()"
        if kind == "native":
            # A standard library function captured in a constant (the value of
            # `import "std:math"`). Resolved against the runtime's namespaces.
            return "tern_lookup_std_member(%s)" % c_string(const["name"])
        raise CodegenError("unsupported constant kind %r" % kind)

    def define_main(self):
        self.emit("// ---- initialisation")
        self.emit("static void init_consts(void) {")
        for index, proto in enumerate(self.protos):
            for const_index, const in enumerate(proto["consts"]):
                target = "K_%d[%d]" % (index, const_index)
                if const["k"] == "type":
                    symbol = self.types[(index, const_index)]
                    for field_index, default in enumerate(const["defaults"]):
                        self.emit("    %s_defaults[%d] = %s;" % (symbol, field_index, self.literal(default)))
                    if any(p >= 0 for p in const["defprotos"]):
                        # Non-literal defaults are evaluated per instance, so they
                        # are stored as a prototype and called from tern_new_instance.
                        for field_index, default_proto in enumerate(const["defprotos"]):
                            if default_proto >= 0:
                                self.emit("    %s_defproto[%d] = closure_new(&P_%d, 0);"
                                          % (symbol, field_index, default_proto))
                    for method_index, (_, method_proto) in enumerate(const["methods"]):
                        self.emit("    %s_methods[%d] = closure_new(&P_%d, 0);"
                                  % (symbol, method_index, method_proto))
                    self.emit("    %s = v_obj((Obj *)&%s);" % (target, symbol))
                elif const["k"] == "map":
                    self.emit("    { Map *m = map_new();")
                    for key, value in const["entries"]:
                        self.emit("      map_set(m, %s, %s);" % (self.literal(key), self.literal(value)))
                    self.emit("      %s = v_obj((Obj *)m); }" % target)
                elif const["k"] == "module":
                    pass   # filled in when the module body runs
                else:
                    self.emit("    %s = %s;" % (target, self.literal(const)))
        self.emit("}")
        self.emit()

        for index, module in enumerate(self.modules):
            count = len(module["globals"])
            self.emit("// ---- module %s" % module["name"])
            self.emit("static Value load_module_%d(void) {" % index)
            self.emit("    if (MODSTATE_%d == 2) return MOD_%d;" % (index, index))
            self.emit("    if (MODSTATE_%d == 1) return MOD_%d;   // cyclic import" % (index, index))
            self.emit("    MODSTATE_%d = 1;" % index)
            self.emit("    tern_bind_globals(G_%d, GN_%d, %d);" % (index, index, count))
            self.emit("    TernFrame module_frame%d;" % index)
            self.emit("    tern_frame_enter(&module_frame%d, &P_%d);" % (index, module["entry"]))
            self.emit("    fn_%d(NULL, 0, NULL);" % module["entry"])
            self.emit("    tern_frame_leave(&module_frame%d);" % index)
            if index == 0 or not module["exports"]:
                self.emit("    MOD_%d = v_nil();" % index)
            else:
                self.emit("    { Map *exports = map_new();")
                for export in module["exports"]:
                    self.emit("      map_set(exports, str_from_cstr(%s), G_%d[%d]);"
                              % (c_string(export["name"]), index, export["slot"]))
                self.emit("      MOD_%d = v_obj((Obj *)exports); }" % index)
            self.emit("    MODSTATE_%d = 2;" % index)
            self.emit("    return MOD_%d;" % index)
            self.emit("}")
            self.emit()

        # Roots the collector cannot find by scanning the stack: constant
        # tables, struct type arrays and the per-module export values.
        self.emit("// ---- collector roots")
        self.emit("static void register_roots(void) {")
        for index, proto in enumerate(self.protos):
            if proto["consts"]:
                self.emit("    tern_gc_register_values(K_%d, %d);" % (index, len(proto["consts"])))
        for (proto_index, const_index), symbol in sorted(self.types.items()):
            const = self.protos[proto_index]["consts"][const_index]
            self.emit("    tern_gc_register_values(%s_defaults, %d);" % (symbol, len(const["fields"])))
            if const["methods"]:
                self.emit("    tern_gc_register_ptrs((void **)%s_methods, %d);" % (symbol, len(const["methods"])))
            if any(p >= 0 for p in const.get("defprotos") or []):
                self.emit("    tern_gc_register_ptrs((void **)%s_defproto, %d);" % (symbol, len(const["fields"])))
        for index in range(len(self.modules)):
            self.emit("    tern_gc_register_values(&MOD_%d, 1);" % index)
        self.emit("}")
        self.emit()

        # The program body lives in its own function so that the collector's
        # stack anchor is in a frame strictly above it: every local of the body
        # (including ones the compiler inlined into it) then sits between the
        # anchor and the current stack pointer.
        self.emit("static int program_main(int argc, char **argv) __attribute__((noinline));")
        self.emit("static int program_main(int argc, char **argv) {")
        self.emit("    (void)argc; (void)argv;")
        self.emit("    tern_program_file = %s;" % c_string(self.modules[0]["name"]))
        self.emit("    tern_rt_init();")
        self.emit("    register_roots();")
        self.emit("    init_consts();")
        self.emit("    load_module_0();")
        self.emit("    fflush(stdout);")
        self.emit("    return 0;")
        self.emit("}")
        self.emit()
        self.emit("int main(int argc, char **argv) {")
        self.emit("    tern_set_args(argc - 1, argv + 1);")
        self.emit("    char tern_stack_anchor = 0;")
        self.emit("    tern_gc_set_stack_bottom(&tern_stack_anchor);")
        self.emit("    return program_main(argc, argv);")
        self.emit("}")


def load(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def main(argv):
    parser = argparse.ArgumentParser(description="Compile TERN bytecode to C/native.")
    parser.add_argument("input", help="bytecode JSON (from `tern emit`) or a .tern script")
    parser.add_argument("-o", "--output", help="output file (.c, or a binary when given a .tern script)")
    parser.add_argument("--cc", default="cc", help="C compiler (default: cc)")
    parser.add_argument("--cflags", default="-O2", help="extra compiler flags")
    parser.add_argument("--keep-c", action="store_true", help="keep generated C next to the binary")
    parser.add_argument("--no-traces", action="store_true",
                        help="drop call-stack bookkeeping (about 10% faster on call-heavy code; "
                             "uncaught errors then report a single line)")
    args = parser.parse_args(argv)

    source = args.input
    temporary = None

    if source.endswith(".tern"):
        import tempfile
        handle, temporary = tempfile.mkstemp(suffix=".json")
        os.close(handle)
        emit = subprocess.run(
            [os.path.join(REPO, "tools", "tern"), "emit", source, "-o", temporary],
            capture_output=True, text=True,
        )
        if emit.returncode != 0:
            sys.stderr.write(emit.stderr or emit.stdout)
            return emit.returncode
        source = temporary

    try:
        module = load(source)
        code = Generator(module, traces=not args.no_traces).generate()
    except CodegenError as error:
        sys.stderr.write("ternc: %s\n" % error)
        return 1
    finally:
        if temporary:
            os.unlink(temporary)

    if args.output is None or args.output.endswith(".c"):
        output = args.output or "app.c"
        with open(output, "w", encoding="utf-8") as handle:
            handle.write(code)
        print("ternc: wrote %s" % output)
        return 0

    import tempfile
    with tempfile.TemporaryDirectory() as build:
        c_path = os.path.join(build, "app.c")
        with open(c_path, "w", encoding="utf-8") as handle:
            handle.write(code)
        command = [args.cc, "-O2", "-I", RUNTIME] + args.cflags.split() + [c_path, "-o", args.output, "-lm"]
        result = subprocess.run(command)
        if result.returncode != 0:
            return result.returncode
        if args.keep_c:
            shutil.copyfile(c_path, args.output + ".c")
    print("ternc: built %s" % args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
