#!/usr/bin/env python3
"""Builds the stand-in shared libraries a headless machine needs for Qt.

Qt links libGL, libEGL, libxkbcommon and libdbus-1 whether or not an
application touches them. On a display-less CI box none of the four are
installed, so importing QtWidgets fails at load time even though the offscreen
platform would never call into them.

This script writes minimal stand-ins whose only job is to satisfy the dynamic
linker: functions are defined as no-ops, and the DBus symbols carry the same
version tags Qt asks for so the loader binds them. The result is enough to
build a widget tree and render it with `QT_QPA_PLATFORM=offscreen`, which is
how the IDE's screenshots and its smoke test are produced.

    python3 tools/ide/qt_stubs.py                 # writes build/qt-stubs/
    QT_STUB_DIR=... python3 tools/ide/qt_stubs.py

On a machine with a display, none of this is needed: the IDE runs normally and
this script is not involved.
"""

import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "build", "qt-stubs")

# soname -> the prefixes of the symbols Qt needs from it. Every Qt library is
# scanned for undefined references, and the ones that match a prefix become
# no-op definitions in the stand-in.
LIBRARIES = {
    "libGL.so.1": ("gl", "glX"),
    "libEGL.so.1": ("egl",),
    "libxkbcommon.so.0": ("xkb",),
    "libdbus-1.so.3": ("dbus_",),
}

STUB_SOURCE = """/* Generated by tools/ide/qt_stubs.py. Do not edit. */
void tern_stub_anchor(void) {}
"""


def qt_lib_dir():
    """Where Qt's own libraries live: from PySide6 if it is importable."""
    override = os.environ.get("TERN_QT_LIB")
    if override:
        return override

    probe = subprocess.run(
        [sys.executable, "-c", "import PySide6, os; print(os.path.join(os.path.dirname(PySide6.__file__), 'Qt', 'lib'))"],
        capture_output=True, text=True)
    if probe.returncode != 0:
        return None

    path = probe.stdout.strip()
    return path if os.path.isdir(path) else None


def undefined_symbols(libraries, prefixes):
    """Undefined symbols matching `prefixes` across `libraries`, as (name, version).

    Reads `nm -D --undefined-only`, whose last field is `name@VERSION`.
    """
    found = set()
    for library in libraries:
        try:
            result = subprocess.run(["nm", "-D", "--undefined-only", library], capture_output=True, text=True)
        except FileNotFoundError:
            return sorted(found)

        if result.returncode != 0:
            continue

        for line in result.stdout.splitlines():
            fields = line.split()
            if not fields:
                continue

            token = fields[-1]
            if token in ("U", "w", "v"):
                continue

            name, _, version = token.partition("@")
            if any(name.startswith(prefix) for prefix in prefixes):
                found.add((name, version or "TERN_STUB"))

    return sorted(found)


def build_stub(name, symbols):
    """Compiles one stand-in library into OUT/name."""
    source = STUB_SOURCE
    script = None
    if symbols:
        by_version = {}
        for symbol, version in symbols:
            by_version.setdefault(version, []).append(symbol)

        source += "".join(f"void {symbol}(void) {{}}\n" for symbol, _ in symbols)
        script = "".join(
            f"{version} {{\n  global:\n" + "".join(f"    {symbol};\n" for symbol in sorted(members)) + "};\n"
            for version, members in sorted(by_version.items()))

    sources = os.path.join(OUT, "src")
    os.makedirs(sources, exist_ok=True)
    work = os.path.join(sources, name + ".c")
    with open(work, "w", encoding="utf-8") as handle:
        handle.write(source)

    command = ["gcc", "-shared", "-fPIC", "-o", os.path.join(OUT, name), work]
    if script:
        mapfile = os.path.join(sources, name + ".map")
        with open(mapfile, "w", encoding="utf-8") as handle:
            handle.write(script)
        command += ["-Wl,--version-script=" + mapfile]

    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        print(result.stderr.strip(), file=sys.stderr)
        return False

    return True


def main():
    os.makedirs(OUT, exist_ok=True)

    lib_dir = qt_lib_dir()
    if lib_dir is None:
        print("qt-stubs: PySide6 is not installed, nothing to inspect", file=sys.stderr)
        return 1

    # Qt's own libraries and its platform plugins: the plugins pull in the GL
    # entry points, so leaving them out produces a stub that cannot host them.
    qt_libraries = sorted(
        os.path.join(lib_dir, entry)
        for entry in os.listdir(lib_dir)
        if entry.startswith("libQt6") and ".so.6" in entry
    )
    plugins = os.path.join(os.path.dirname(lib_dir), "plugins")
    for directory, _subdirs, names in os.walk(plugins):
        qt_libraries += [os.path.join(directory, name) for name in names if name.endswith(".so")]

    written = 0
    for name, prefixes in LIBRARIES.items():
        symbols = undefined_symbols(qt_libraries, prefixes)
        if not build_stub(name, symbols):
            print(f"qt-stubs: could not build {name}", file=sys.stderr)
            return 1

        written += 1

    print(f"qt-stubs: wrote {written} stand-ins to {os.path.relpath(OUT, ROOT)}")
    print(f"qt-stubs: use LD_LIBRARY_PATH={os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
