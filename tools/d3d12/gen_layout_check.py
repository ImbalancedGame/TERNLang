#!/usr/bin/env python3
"""Generate the layout check that keeps the Direct3D 12 mirror honest.

runtime/tern_d3d12.h spells out the Direct3D 12 structures by hand, because the
native backend has to build on machines without the Windows SDK. Each structure
carries a `_Static_assert` with the size and offsets printed from the shipped
d3d12.h. This script reads those assertions and writes the same assertions
against the real header, which the Windows build compiles: if the mirror and the
SDK ever disagree, that build fails instead of the runtime corrupting memory.

    python3 tools/d3d12/gen_layout_check.py > build/layout_check.c
    zig cc -target x86_64-windows-gnu -c build/layout_check.c
"""

import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(REPO, "native", "runtime", "tern_d3d12.h")

# The mirror uses snake_case field names; the SDK uses the names from the header.
FIELDS = {
    "cpu_page_property": "CPUPageProperty",
    "width": "Width",
    "format": "Format",
    "footprint": "Footprint",
    "blend_state": "BlendState",
    "rasterizer_state": "RasterizerState",
    "input_layout": "InputLayout",
    "render_target_formats": "RTVFormats",
    "description": "pDescription",
    "description_bytes": "DescriptionByteLength",
}

# Unions are named after their member in the SDK, and the member differs per type.
UNIONS = {
    "D3D12_RESOURCE_BARRIER": "Transition",
    "D3D12_TEXTURE_COPY_LOCATION": "PlacedFootprint",
    # The SDK's clear value has an anonymous union holding Color[4].
    "D3D12_CLEAR_VALUE": "Color",
}

SIZE = re.compile(r"_Static_assert\(sizeof\((\w+)\)\s*==\s*(\d+)\s*,")
OFFSET = re.compile(r"_Static_assert\(offsetof\((\w+),\s*(\w+)\)\s*==\s*(\d+)\s*,")


def main():
    text = open(HEADER, encoding="utf-8").read()
    checks = []

    for name, expected in SIZE.findall(text):
        checks.append(
            f'_Static_assert(sizeof({name}) == {expected}, "{name} size");'
        )

    for name, field, expected in OFFSET.findall(text):
        sdk_field = UNIONS[name] if field == "u" and name in UNIONS else FIELDS.get(field)
        if sdk_field is None:
            sdk_field = "".join(part.capitalize() for part in field.split("_"))
        checks.append(
            f'_Static_assert(offsetof({name}, {sdk_field}) == {expected}, '
            f'"{name}.{sdk_field} offset");'
        )

    print("// Generated by tools/d3d12/gen_layout_check.py. Do not edit.")
    print("// The same numbers as native/runtime/tern_d3d12.h, checked against the")
    print("// real d3d12.h. A mismatch is a compile error.")
    print("#include <stddef.h>")
    print("#include <windows.h>")
    print("#include <d3d12.h>")
    print()
    for check in checks:
        print(check)
    print()
    print(f"// {len(checks)} checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
