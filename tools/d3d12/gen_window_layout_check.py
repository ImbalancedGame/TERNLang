#!/usr/bin/env python3
"""Generate the layout check for the Win32 structures in tern_window.h.

`native/runtime/tern_window.h` writes WNDCLASSEXW, MSG, BITMAPINFOHEADER,
BITMAPINFO and RECT out by hand, with a `_Static_assert` for every size and
offset. This script rewrites those assertions against the real windows.h, which
the Windows build compiles: if the mirror and the SDK ever disagree, that build
fails rather than the window corrupting memory on its first frame.

    python3 tools/d3d12/gen_window_layout_check.py > build/window_layout_check.c
    zig cc -target x86_64-windows-gnu -c build/window_layout_check.c

The field names are mapped explicitly because the mirror is snake_case and the
SDK is not; there is no cleverness here on purpose, since a wrong mapping would
quietly check the wrong field.
"""

import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(REPO, "native", "runtime", "tern_window.h")

# mirror struct -> the SDK struct it claims to be
NAMES = {
    "TernWinRect": "RECT",
    "TernWinClass": "WNDCLASSEXW",
    "TernWinMsg": "MSG",
    "TernBitmapHeader": "BITMAPINFOHEADER",
    "TernBitmapInfo": "BITMAPINFO",
}

# mirror field -> SDK field, for the fields the mirror gives a different name
FIELDS = {
    "TernWinClass": {
        "cb_size": "cbSize",
        "proc": "lpfnWndProc",
        "cls_extra": "cbClsExtra",
        "wnd_extra": "cbWndExtra",
        "instance": "hInstance",
        "icon": "hIcon",
        "cursor": "hCursor",
        "background": "hbrBackground",
        "menu": "lpszMenuName",
        "class_name": "lpszClassName",
        "icon_small": "hIconSm",
    },
    "TernWinMsg": {
        "hwnd": "hwnd",
        "message": "message",
        "wparam": "wParam",
        "lparam": "lParam",
        "time": "time",
        # MSG holds a POINT; the mirror spells its two fields out.
        "x": "pt.x",
        "y": "pt.y",
    },
    "TernWinRect": {"left": "left", "top": "top", "right": "right", "bottom": "bottom"},
    "TernBitmapHeader": {
        "size": "biSize",
        "width": "biWidth",
        "height": "biHeight",
        "planes": "biPlanes",
        "bits": "biBitCount",
        "compression": "biCompression",
        "size_image": "biSizeImage",
        "x_ppm": "biXPelsPerMeter",
        "y_ppm": "biYPelsPerMeter",
        "colours_used": "biClrUsed",
        "colours_important": "biClrImportant",
    },
    "TernBitmapInfo": {"header": "bmiHeader", "colour0": "bmiColors"},
}

SIZE = re.compile(r"_Static_assert\(sizeof\((\w+)\)\s*==\s*(\d+)\s*,")
OFFSET = re.compile(r"_Static_assert\(offsetof\((\w+),\s*(\w+)\)\s*==\s*(\d+)\s*,")


def main():
    text = open(HEADER, encoding="utf-8").read()
    problems = []
    checks = []

    for mirror, expected in SIZE.findall(text):
        sdk = NAMES.get(mirror)
        if sdk is None:
            problems.append(f"{mirror} has a size assertion but no SDK name")
            continue
        checks.append(f'_Static_assert(sizeof({sdk}) == {expected}, "{sdk} size");')

    for mirror, field, expected in OFFSET.findall(text):
        sdk = NAMES.get(mirror)
        if sdk is None:
            problems.append(f"{mirror}.{field} has an offset assertion but no SDK name")
            continue
        sdk_field = FIELDS.get(mirror, {}).get(field)
        if sdk_field is None:
            problems.append(f"{mirror}.{field} has no SDK field name")
            continue
        checks.append(
            f'_Static_assert(offsetof({sdk}, {sdk_field}) == {expected}, '
            f'"{sdk}.{sdk_field} offset");'
        )

    if problems:
        for problem in problems:
            print(f"gen_window_layout_check: {problem}", file=sys.stderr)
        return 1

    if not checks:
        print("gen_window_layout_check: no assertions found in tern_window.h", file=sys.stderr)
        return 1

    print("// Generated by tools/d3d12/gen_window_layout_check.py - do not edit.")
    print("// Compiled against the real windows.h by tools/test-d3d12.sh.")
    print("#include <windows.h>")
    print("#include <stddef.h>")
    print()
    for check in checks:
        print(check)
    return 0


if __name__ == "__main__":
    sys.exit(main())
